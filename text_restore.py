def _detect_lang():
    """按系统区域自动选择默认语言。"""
    try:
        import locale
        lang, _ = locale.getdefaultlocale()
    except Exception:
        lang = ''
    return 'zh' if (lang or '').lower().startswith('zh') else 'en'


