    # ---------- 窗口几何记忆 ----------
    def _apply_saved_geometry(self, cfg):
        """恢复上次的窗口尺寸与位置 (校验最小值与屏幕可见性)。"""
        geo = cfg.get('win_geometry')
        if not isinstance(geo, str):
            return False
        m = re.match(r'^(\d+)x(\d+)([+-]\d+)([+-]\d+)$', geo.strip())
        if not m:
            return False
        w, h = int(m.group(1)), int(m.group(2))
        if w < 860 or h < 400:          # 小于最小尺寸则用默认
            return False
        sw = self.root.winfo_screenwidth()
        sh = self.root.winfo_screenheight()
        w, h = min(w, sw), min(h, sh)
        x, y = int(m.group(3)), int(m.group(4))
        # 允许副屏负坐标, 但保证至少有 120x80 留在屏幕内
        x = max(-(w - 120), min(x, sw - 120))
        y = max(0, min(y, sh - 80))
        self.root.geometry(f'{w}x{h}+{x}+{y}')
        self._win_geom = f'{w}x{h}+{x}+{y}'
        st = cfg.get('win_state')
        if st in ('normal', 'zoomed'):
            self._win_state = st
        return True

    def restore_window_state(self):
        """窗口显示后应用"最大化"状态。"""
        if self._win_state == 'zoomed':
            try:
                self.root.state('zoomed')
            except tk.TclError:
                pass

    def _on_window_configure(self, event):
        """记录窗口尺寸/位置 (忽略子控件事件与最小化状态)。"""
        if event.widget is not self.root:
            return
        if event.width < 200 or event.height < 150:
            return          # 未映射/最小化时的异常尺寸
        try:
            st = self.root.state()
        except tk.TclError:
            return
        if st == 'zoomed':
            self._win_state = 'zoomed'
            return
        if st != 'normal':
            return
        self._win_state = 'normal'
        self._win_geom = f'{event.width}x{event.height}+{event.x}+{event.y}'

    def _apply_window_icon(self):
        """让窗口标题栏使用应用图标。

        iconbitmap 负责 Windows 原生图标; iconphoto 用 PNG 双保险
        (打包后从 _MEIPASS 读取捆绑的 icon_preview.png)。
        """
        try:
            if getattr(sys, 'frozen', False):
                self.root.iconbitmap(default=sys.executable)
            else:
                self.root.iconbitmap(ICON_PATH)
        except tk.TclError:
            pass
        try:
            png = os.path.join(getattr(sys, '_MEIPASS', APP_DIR),
                               'icon_preview.png')
            self._icon_photo = tk.PhotoImage(file=png)
            self.root.iconphoto(True, self._icon_photo)
        except tk.TclError:
            pass

