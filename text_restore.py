# ---------------- 日期时间格式还原 (中文 -> 标准英文格式) ----------------
# 识别 2024年1月5日 / 1月5号 / 下午3点15分 / 二零二四年 等中文格式,
# 转换为 ISO 8601 风格: 2024-01-05 15:15

_CN_DIGITS = {'零': 0, '〇': 0, '一': 1, '二': 2, '两': 2, '三': 3, '四': 4,
              '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}
_NUM = r'(?:\d{1,4}|[零〇一二两三四五六七八九十百千]{1,8})'
_AP = r'凌晨|清晨|早上|上午|中午|正午|下午|傍晚|晚上|深夜|晚'
# 时间尾部: 点[半][M分][S秒][钟]
_TIME_TAIL = (r'\s*点\s*(?P<half>半)?'
              r'(?:\s*(?P<mi>' + _NUM + r')\s*分)?'
              r'(?:\s*(?P<se>' + _NUM + r')\s*秒)?'
              r'\s*(?P<zh>钟)?')

_RE_DATETIME = re.compile(
    r'(?:(?P<ap1>' + _AP + r')\s*)?(?<!\d)(?P<y>' + _NUM + r')\s*年\s*'
    r'(?P<m>' + _NUM + r')\s*月\s*'
    r'(?P<d>' + _NUM + r')\s*[日号]?'
    r'(?:\s*(?:(?P<ap2>' + _AP + r')\s*)?(?<!\d)(?P<h>' + _NUM + r')'
    + _TIME_TAIL + r')?'
)
_RE_YEAR_MONTH = re.compile(
    r'(?<!\d)(?P<y>' + _NUM + r')\s*年\s*(?P<m>' + _NUM + r')\s*月(?!\d)'
)
_RE_MONTH_DAY = re.compile(
    r'(?<!\d)(?P<m>' + _NUM + r')\s*月\s*(?P<d>' + _NUM + r')\s*[日号]'
)
_RE_TIME = re.compile(
    r'(?:(?P<ap>' + _AP + r')\s*)?(?<!\d)(?P<h>' + _NUM + r')'
    + _TIME_TAIL
)


def _cn_to_int(s):
    """中文数字(支持 零〇一二两三四五六七八九十百千 与阿拉伯数字) -> int。"""
    if not s:
        return None
    if s.isdigit():
        return int(s)
    if all(c in _CN_DIGITS for c in s):
        # 逐位数字, 如 二零二四 -> 2024
        n = 0
        for c in s:
            n = n * 10 + _CN_DIGITS[c]
        return n
    # 含 十/百/千 的位置计数法, 如 二十五 -> 25
    total = 0
    section = 0
    for c in s:
        if c in _CN_DIGITS:
            section = _CN_DIGITS[c]
        elif c == '十':
            section = 10 if section == 0 else section * 10
            total += section
            section = 0
        elif c == '百':
            section = 100 if section == 0 else section * 100
            total += section
            section = 0
        elif c == '千':
            section = 1000 if section == 0 else section * 1000
            total += section
            section = 0
        else:
            return None
    total += section
    return total if total > 0 else None


def _int_of(m, name):
    return _cn_to_int(m.group(name))


def _format_hms(ap, h, mi, se, half=False):
    """把 点/分/秒 与上下午标记格式化为 24 小时制 HH:MM[:SS]。"""
    if h is None or not (0 <= h <= 23):
        return None
    ap = ap or ''
    if ap in ('下午', '傍晚', '晚上', '深夜', '晚'):
        if h < 12:
            h += 12
    elif ap in ('中午', '正午'):
        if h < 12:
            h += 12
    elif ap == '凌晨':
        if h == 12:
            h = 0
    if not (0 <= h <= 23):
        return None
    if half:
        mi = 30
    if mi is not None and not (0 <= mi <= 59):
        return None
    if se is not None and not (0 <= se <= 59):
        return None
    out = f'{h:02d}:{0 if mi is None else mi:02d}'
    if se is not None:
        out += f':{se:02d}'
    return out


def _has_time_marker(m):
    """"点"是否有消歧标记 (上下午/分/秒/半/钟), 或小时是阿拉伯数字。

    中文数字的"X点"在中文里常表示量词(一点=少许/两点意见/晚一点),
    无强标记时不转换; 裸"晚"只算弱标记, 仅配合阿拉伯数字生效(晚8点)。
    """
    g = m.groupdict()
    h = g.get('h') or ''
    if h.isdigit():
        return True          # 阿拉伯/全角数字 + 点, 基本都是时间
    for key in ('ap', 'ap2'):
        ap = g.get(key)
        if ap and ap != '晚':
            return True      # 上午/下午/晚上... 等强标记
    return bool(g.get('half') or g.get('zh')
                or g.get('mi') or g.get('se'))


def _format_datetime(m):
    y, mo, d = _int_of(m, 'y'), _int_of(m, 'm'), _int_of(m, 'd')
    if None in (y, mo, d) or not (1 <= y <= 9999 and 1 <= mo <= 12 and 1 <= d <= 31):
        return None
    date = f'{y:04d}-{mo:02d}-{d:02d}'
    h = _int_of(m, 'h')
    if h is None:
        return date
    ts = _format_hms(m.group('ap2') or m.group('ap1'), h,
                     _int_of(m, 'mi'), _int_of(m, 'se'),
                     half=bool(m.group('half')))
    if ts is None:
        return None
    return f'{date} {ts}'


def _format_year_month(m):
    y, mo = _int_of(m, 'y'), _int_of(m, 'm')
    if None in (y, mo) or not (1 <= mo <= 12):
        return None
    return f'{y:04d}-{mo:02d}'


def _format_month_day(m):
    mo, d = _int_of(m, 'm'), _int_of(m, 'd')
    if None in (mo, d) or not (1 <= mo <= 12 and 1 <= d <= 31):
        return None
    return f'{mo:02d}-{d:02d}'


def _format_time(m):
    if not _has_time_marker(m):
        return None   # 无消歧标记的中文数字"X点" -> 量词, 不转换
    return _format_hms(m.group('ap'), _int_of(m, 'h'),
                       _int_of(m, 'mi'), _int_of(m, 'se'),
                       half=bool(m.group('half')))


def _find_datetime_segments(text):
    """找出文本中的中文日期时间片段, 返回 [(start, end, 替换串), ...] (不重叠)。"""
    found = []
    for m in _RE_DATETIME.finditer(text):
        r = _format_datetime(m)
        if r is not None:
            found.append((m.start(), m.end(), r))
    for m in _RE_YEAR_MONTH.finditer(text):
        r = _format_year_month(m)
        if r is not None:
            found.append((m.start(), m.end(), r))
    for m in _RE_MONTH_DAY.finditer(text):
        r = _format_month_day(m)
        if r is not None:
            found.append((m.start(), m.end(), r))
    for m in _RE_TIME.finditer(text):
        r = _format_time(m)
        if r is not None:
            found.append((m.start(), m.end(), r))
    return found


# ---------------- AI 提示词标记 & 署名注释 ----------------
# 模型输出中残留的系统标记/提示词 token (来自 remove-ai-watermark 等工具清单)
_TOKEN_RE = re.compile(
    r'<\|im_start\|>|<\|im_end\|>|\[INST\]|\[/INST\]|<\|endoftext\|>|'
    r'<\|endofpiece\|>|<\|system\|>|<\|user\|>|<\|assistant\|>|'
    r'<\|begin_of_text\|>|<\|end_of_text\|>|<\|eot_id\|>|'
    r'<\|startoftext\|>|<\|sep\|>|<\|cls\|>|<\|pad\|>',
    re.IGNORECASE)

# AI 署名注释特征 (comment 行匹配则移除)
_AI_COMMENT_RE = re.compile(
    r'auto-generated by ai|generated by ai|created by ai|written by ai|'
    r'co-authored-by: ai|ai-generated code|ai generated|ai watermark',
    re.IGNORECASE)
_COMMENT_PREFIXES = ('//', '#', '<!--', '--', '/*')


def _find_token_segments(text):
    """找出 LLM 提示词标记段 [(start, end, ''), ...]。"""
    return [(m.start(), m.end(), '') for m in _TOKEN_RE.finditer(text)]


def _find_ai_comment_segments(text):
    """找出 AI 署名注释行 (整行移除, 含换行)。"""
    segs = []
    pos = 0
    n = len(text)
    while pos < n:
        nl = text.find('\n', pos)
        if nl == -1:
            nl = n
        line = text[pos:nl]
        trimmed = line.strip()
        if trimmed.startswith(_COMMENT_PREFIXES) and _AI_COMMENT_RE.search(line):
            end = nl + 1 if nl < n else nl
            segs.append((pos, end, ''))
        pos = nl + 1
    return segs


def _merge_ranges(ranges):
    """把区间排序并合并相邻区间, 减少 Tk 标注次数。"""
    if not ranges:
        return []
    ranges = sorted(ranges)
    merged = [list(ranges[0])]
    for s, e in ranges[1:]:
        if s <= merged[-1][1]:
            if e > merged[-1][1]:
                merged[-1][1] = e
        else:
            merged.append([s, e])
    return [(a, b) for a, b in merged]


def convert_text(text, enabled):
    """按启用选项转换文本。

    返回 (结果字符串, {分类: 替换数量}, 输入中被替换的区间, 输出中还原结果的区间,
          映射信息)。
    区间为 [(起始下标, 结束下标), ...] 形式, 已合并相邻区间, 用于 diff 高亮。
    末尾的换行符(\n / \r)会被删除, 并在输入区间中标注出来。
    中文日期时间(2024年1月5日下午3点)会转换为标准格式并标注。
    映射信息用于选中区域联动:
        'in_to_out_start': 每个输入字符对应的输出起点(含末尾哨兵)
        'out_to_in'       : 每个输出字符对应的输入下标
        'cut'             : 参与转换的输入长度(末尾换行被排除)
    """
    order = [k for k in MAPPINGS if enabled.get(k, True)]
    counts = {k: 0 for k in order}
    red = []     # 输入中发生替换的区间
    green = []   # 输出中替换结果的区间

    # 末尾换行处理: 删除末尾所有 \n / \r, 在输入中标注
    cut = len(text)
    if enabled.get('trailing', True):
        while cut > 0 and text[cut - 1] in '\r\n':
            cut -= 1
        if cut < len(text):
            counts['trailing'] = len(text) - cut
            red.append((cut, len(text)))

    out = []
    out_pos = 0
    in_to_out_start = []   # 每个输入字符对应的输出起点
    in_to_out_end = []     # 每个输入字符对应的输出终点
    out_to_in = []         # 每个输出字符对应的输入下标

    def convert_range(in_start, in_end):
        """逐字符转换 [in_start, in_end) 区间。"""
        nonlocal out_pos
        for in_pos in range(in_start, in_end):
            in_to_out_start.append(out_pos)
            ch = text[in_pos]
            new = ch
            changed = False
            for k in order:
                n = MAPPINGS[k].get(new, new)
                if n != new:
                    counts[k] += 1
                    new = n
                    changed = True
            if changed:
                red.append((in_pos, in_pos + 1))
                if new:
                    green.append((out_pos, out_pos + len(new)))
            out.append(new)
            out_pos += len(new)
            in_to_out_end.append(out_pos)
            for _ in new:
                out_to_in.append(in_pos)

    def convert_dt(in_start, in_end, repl, key='datetime'):
        """把一段区间替换为 repl (空串=整段删除) 并标注。"""
        nonlocal out_pos
        counts[key] = counts.get(key, 0) + 1
        red.append((in_start, in_end))
        new_end = out_pos + len(repl)
        for _ in range(in_start, in_end):
            in_to_out_start.append(out_pos)
            in_to_out_end.append(new_end)
        if repl:
            green.append((out_pos, out_pos + len(repl)))
            out.append(repl)
            out_pos += len(repl)
            for _ in repl:
                out_to_in.append(in_start)
        # repl 为空串: 整段删除, 不产生任何输出

    # 段落级替换: 日期时间 / AI 提示词标记 / AI 署名注释 (按 key 统计)
    segments = []
    if enabled.get('datetime', True):
        segments.extend((s, e, r, 'datetime')
                        for s, e, r in _find_datetime_segments(text[:cut]))
    if enabled.get('tokens', True):
        segments.extend((s, e, r, 'tokens')
                        for s, e, r in _find_token_segments(text[:cut]))
    if enabled.get('comments', False):
        segments.extend((s, e, r, 'comments')
                        for s, e, r in _find_ai_comment_segments(text[:cut]))
    # 按起点排序, 起点相同取较长匹配; 跳过重叠
    segments.sort(key=lambda x: (x[0], -(x[1] - x[0])))
    merged = []
    last_end = -1
    for s, e, r, k in segments:
        if s >= last_end:
            merged.append((s, e, r, k))
            last_end = e
    pos = 0
    for s, e, r, k in merged:
        if s > pos:
            convert_range(pos, s)
        convert_dt(s, e, r, key=k)
        pos = e
    if pos < cut:
        convert_range(pos, cut)

    in_to_out_start.append(out_pos)   # 哨兵: 输入末尾之后
    return ''.join(out), counts, _merge_ranges(red), _merge_ranges(green), {
        'in_to_out_start': in_to_out_start,
        'in_to_out_end': in_to_out_end,
        'out_to_in': out_to_in,
        'cut': cut,
    }


def _line_starts(s):
    """返回每行在字符串中的起始偏移(第 1 行从 0 开始)。"""
    starts = [0]
    for i, ch in enumerate(s):
        if ch == '\n':
            starts.append(i + 1)
    return starts


def _idx_to_offset(index, line_starts):
    """Tk 文本索引 'line.col' -> 字符偏移。"""
    line, col = (int(x) for x in index.split('.'))
    return line_starts[line - 1] + col


def _offset_to_index(offset, line_starts, total_len):
    """字符偏移 -> Tk 文本索引 'line.col'。"""
    offset = max(0, min(offset, total_len))
    li = bisect.bisect_right(line_starts, offset) - 1
    return f'{li + 1}.{offset - line_starts[li]}'


