    # ---------- 同步滚动 ----------
    def _scroll_both(self, *args):
        """滚动条拖动时, 两个文本框一起滚动。"""
        if self._syncing:
            return
        self._syncing = True
        try:
            self.input_text.yview(*args)
            self.output_text.yview(*args)
        finally:
            self._syncing = False

    def _wheel_both(self, event):
        """滚轮事件: 两个文本框一起滚动。"""
        delta = getattr(event, 'delta', 0)
        if delta:
            steps = -1 if delta > 0 else 1
            if abs(delta) >= 120:
                steps = -delta // 120
        else:
            steps = 1 if event.num == 4 else -1
        if not self._syncing:
            self._syncing = True
            try:
                self.input_text.yview_scroll(steps, 'units')
                self.output_text.yview_scroll(steps, 'units')
            finally:
                self._syncing = False
        return 'break'

    def _sync_output_view(self):
        """把输出框滚动位置对齐到输入框。"""
        if self._syncing:
            return
        self._syncing = True
        try:
            frac, _ = self.input_text.yview()
            self.output_text.yview_moveto(frac)
        finally:
            self._syncing = False

